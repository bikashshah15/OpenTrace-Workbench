// Stage 4: the live AI-layer banner is derived from the actual AI-BOM card (generated here / requested but not delivered / none), never from source references.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { liveAiNote, LIVE_LAYER_NOTE, LAYER_NOTE } from '../../../src/ui/lib/copy.js';

const card = (outcome) => ({ kind: 'aibom', artifact_name: 'cisco-aibom.cdx.json', scan: { outcome } });
test('no AI-BOM card: no inventory available, source observations are not an inventory', () => {
  const t = liveAiNote({ cards: [{ kind: 'sbom' }, { kind: 'cbom' }], model_references: 3 });
  assert.match(t, /^No AI inventory is available for this live scan: the AI-BOM phase did not run/); assert.match(t, /not an inventory/);
  assert.doesNotMatch(t, /needs a provider|not part of this slice|generated in this live scan/);
});
test('source model references in the summary never create an inventory claim', () => {
  assert.match(liveAiNote({ cards: [], model_references: [{ locator: 'x' }], ai_source: { runtimes: [1] } }), /^No AI inventory is available/);
  assert.match(liveAiNote(undefined), /^No AI inventory is available/);
});
const page = (outcome) => ({ producers: [{ provenance: { origin: 'supplemental_observation' }, outcome: 'completed' }, ...(outcome ? [{ provenance: { origin: 'original_artifact' }, outcome }] : [])] });
test('an acquired AI-BOM card: inventory generated in this scan by Cisco AI-BOM, separately from Syft and cdxgen', () => {
  const t = liveAiNote({ cards: [card('acquired')] }, page('completed'));
  assert.match(t, /generated in this live scan by Cisco AI-BOM, separately from Syft and cdxgen/); assert.doesNotMatch(t, /^No AI inventory/);
});
test('generated-valid but partial: says partial, still generated by Cisco AI-BOM', () => {
  const t = liveAiNote({ cards: [card('acquired')] }, page('partial'));
  assert.match(t, /is partial/); assert.match(t, /Cisco AI-BOM/);
});
test('acquired-invalid (validated payload has a failed/absent AI-BOM producer): no inventory is implied', () => {
  for (const p of [page('failed'), page(null), page('not_run'), page('unsupported')]) {
    const t = liveAiNote({ cards: [card('acquired')] }, p);
    assert.match(t, /^No AI inventory is available for this live scan: the AI-BOM was acquired but/); assert.doesNotMatch(t, /was generated|generated in this live scan/);
  }
  assert.doesNotMatch(liveAiNote({ cards: [card('acquired')] }, { producers: [] }), /generated/);
});
test('acquired but the validated payload is not loaded yet: no generation claim', () => {
  const t = liveAiNote({ cards: [card('acquired')] }, undefined);
  assert.doesNotMatch(t, /generated|^No AI inventory/); assert.match(t, /once the validated AI inventory view is available/);
});
test('source producers never stand in for the AI-BOM producer', () => {
  assert.doesNotMatch(liveAiNote({ cards: [card('acquired')] }, { producers: [{ provenance: { origin: 'supplemental_observation' }, outcome: 'completed' }] }), /generated/);
});
test('separately supplied / captured inventory keeps the captured note (liveAiNote is used for live mode only)', () => {
  assert.match(LAYER_NOTE.ai, /AI-BOM/);
  assert.doesNotMatch(LAYER_NOTE.ai, /generated in this live scan/);
});
test('a requested AI-BOM that did not deliver (failed/cancelled/timeout): no inventory available, never "generated"', () => {
  for (const o of ['failed', 'cancelled', 'timeout', undefined]) { const t = liveAiNote({ cards: [card(o)] }, page('completed')); assert.match(t, /^No AI inventory is available for this live scan: an AI-BOM was requested/); assert.doesNotMatch(t, /was generated/); }
});
test('the static live AI note is gone and the Workbench uses the derived note for the AI tab in live mode only', () => {
  assert.equal('ai' in LIVE_LAYER_NOTE, false);
  const src = readFileSync(new URL('../../../src/ui/components/workbench.js', import.meta.url), 'utf8');
  // UI-EVIDENCE-STATUS-01: the derived AI note moved into the evidence strip's Details (same derivation, never claimed in the layer note again).
  assert.ok(src.includes("isLive(s) && (tab === 'ai' || tab === 'crypto') ? '' :"));   // no static captured note under a live AI/crypto strip
  const model = readFileSync(new URL('../../../src/ui/lib/evidence_status.js', import.meta.url), 'utf8');
  assert.ok(model.includes("liveAiNote(s.analysis.summary, s.views?.aiPage)"));
});
