"""Implemented rule: model_identity.digest/2 (declared digest vs separately observed artifact digest).

Scope depends on the artifact class of the declared entity (docs/ARCHITECTURE.md, "Artifact classes").
A file digest never establishes that a runtime loaded the file; `execution` is not examined.
"""

from . import rules_aibom, rules_cbom, rules_cbom3, rules_cbom4, rules_inventory, rules_mapping
from .assess import DIGEST_LENGTHS, assertion_scope_gaps, assess_state, check_evidence_scope, digest_error  # noqa: F401

RULE_ID = "model_identity.digest/2"
OBSERVATION_KIND = "artifact_digest"

# class -> (required scope fields, what a result means)
CLASSES = {
    "committed_file": (("revision",),
                       "digest of the file at the stated repository path and revision"),
    "build_output": (("build",),
                     "digest of a file inside the identified build's output; source revision alone does not identify generated bytes"),
    "external_acquisition": ((),
                             "digest of bytes retrieved from the stated acquisition locator; not bound to any source revision"),
}


def _norm_locator(s):
    s = s.strip()
    while s.startswith("./"):
        s = s[2:]
    return s


def is_digest_assertion(a):
    return a["family"] == "model_identity" and a["predicate"] == "has_digest"


def declared_locators(entity):
    return sorted({_norm_locator(x) for x in entity.get("artifact", {}).get("locators", [])})


def _compare(declared, obs):
    """Relation of one used observation to the declared digest (inputs already validated)."""
    if not obs.get("value") or not obs.get("algorithm"):
        return "inconclusive", "digest_not_observed", "observation carries no algorithm/value"
    if obs["algorithm"] != declared["algorithm"]:
        return "inconclusive", "algorithm_mismatch", (
            f"declared {declared['algorithm']}, observed {obs['algorithm']}; digests are not comparable")
    if obs["value"].lower() == declared["value"].lower():
        return "supports", "digest_equal", "same algorithm, equal digest"
    return "contradicts", "digest_different", "same algorithm, different digest for the matched artifact"


def _base(assertion):
    return {
        "finding_id": "finding:" + assertion["assertion_id"], "assertion_id": assertion["assertion_id"],
        "rule_id": None, "scope_id": assertion["scope_id"],
        "applicability": {"applicable": None, "reason_code": "rule_not_implemented", "reason": ""},
        "state": None, "reason_codes": [], "rationale": "", "used_evidence": [], "excluded_evidence": [],
        "underlying_sources": [], "shared_underlying_sources": {},
        "artifact_class": None, "required_scope": [], "bounded_meaning": None,
        "assertion_origin": assertion["origin"], "evidence_origins": [],
        "category": None, "next_action": None,
    }


def assess(assertion, entities, evidence, inventories=None):
    """Dispatch to the rule for this assertion; return its finding (deterministic; evidence sorted by id)."""
    f = _base(assertion)
    if rules_cbom4.applies(assertion):   # UIP-12: must precede the version-agnostic /2 branch below
        return rules_cbom4.assess(f, assertion, entities, evidence, inventories or {})
    if rules_cbom3.applies(assertion):
        return rules_cbom3.assess(f, assertion, entities, evidence, inventories or {})
    if rules_cbom.applies(assertion):
        return rules_cbom.assess(f, assertion, entities, evidence, inventories or {})
    if rules_mapping.applies(assertion):
        return rules_mapping.assess(f, assertion, entities, evidence, inventories or {})
    if rules_aibom.applies(assertion):
        return rules_aibom.assess(f, assertion, entities, evidence, inventories or {})
    if rules_inventory.applies(assertion):
        return rules_inventory.assess(f, assertion, entities, evidence, inventories or {})
    return assess_digest(f, assertion, entities, evidence)


def assess_digest(f, assertion, entities, evidence):
    if not is_digest_assertion(assertion):
        why = f"no rule is implemented for {assertion['family']}/{assertion['predicate']}; applicability not established"
        f["applicability"]["reason"] = why
        f.update(state="unverifiable", reason_codes=["rule_not_implemented"],
                 rationale="Unverifiable: " + why + ". The relationship is a declaration only.")
        return f

    f["rule_id"] = RULE_ID
    f["applicability"] = {"applicable": True, "reason_code": "digest_declared",
                          "reason": "assertion declares a digest for an artifact"}
    entity = entities[assertion["subject"]]
    cls = entity.get("artifact", {}).get("class")
    locs = declared_locators(entity)
    f["artifact_class"] = cls
    exclude = lambda e, c, d: f["excluded_evidence"].append({"evidence_id": e["evidence_id"], "reason_code": c, "detail": d})
    # Artifact correspondence comes first and never looks at digest values: a candidate is a digest
    # observation whose artifact locator equals a locator the entity declares. Observations of other
    # artifacts are not candidates and are not listed as exclusions.
    candidates = sorted((e for e in evidence if e["observation"].get("kind") == OBSERVATION_KIND
                         and _norm_locator(e["observation"]["artifact"]["locator"]) in locs),
                        key=lambda e: e["evidence_id"])

    required = None
    if cls is None or cls not in CLASSES:
        code = "artifact_class_unspecified" if cls is None else "artifact_class_unsupported"
        f["reason_codes"].append(code)
        for e in candidates:
            exclude(e, code, f"artifact class {cls!r} is not supported by this rule")
        why = "the entity declares no artifact class" if cls is None else f"artifact class {cls!r} is unsupported"
        f["rationale"] = f"Unverifiable: {why}; supported classes: {sorted(CLASSES)}."
    else:
        required = list(CLASSES[cls][0]) + (["configuration"] if assertion.get("depends_on_configuration") else [])
        f["required_scope"] = required
        f["bounded_meaning"] = CLASSES[cls][1] + (
            "; assertion depends on the selecting configuration" if "configuration" in required else "") + \
            "; runtime loading is not established"
        gaps = assertion_scope_gaps(required, assertion["scope"])
        if gaps:
            f["reason_codes"].append("assertion_scope_incomplete")
            for e in candidates:
                exclude(e, "assertion_scope_incomplete", "assertion lacks required scope: " + ", ".join(gaps))
            f["rationale"] = "Unverifiable: assertion lacks required scope field(s) " + ", ".join(gaps) + \
                f" for a {cls} artifact; evidence cannot be bound to it."
        elif len(locs) != 1:
            code = "artifact_identity_unknown" if not locs else "artifact_identity_ambiguous"
            f["reason_codes"].append(code)
            for e in candidates:
                exclude(e, code, f"declared artifact locators: {locs}")
            f["rationale"] = ("Unverifiable: the declared entity names no artifact locator, so no observation can be matched to it."
                              if not locs else
                              f"Unverifiable: the declared entity names several candidate artifacts {locs}; no single artifact is matched.")
        else:
            for e in candidates:
                if e["scope_id"] != assertion["scope_id"]:
                    exclude(e, "capture_mismatch", f"evidence capture {e['scope_id']!r} vs assertion capture {assertion['scope_id']!r}")
                    continue
                ok, code, detail = check_evidence_scope(required, assertion["scope"], e["scope"])
                if not ok:
                    exclude(e, code, detail)
                    continue
                if cls == "external_acquisition":
                    r = e["observation"].get("retrieval") or {}
                    if not (r.get("method") and r.get("source") and _norm_locator(r["source"]) == locs[0]):
                        exclude(e, "retrieval_metadata_missing", "externally acquired artifact needs retrieval.source (= acquisition locator) and retrieval.method")
                        continue
                rel, rcode, rdetail = _compare(assertion["object"], e["observation"])
                f["used_evidence"].append({"evidence_id": e["evidence_id"], "role": "observation", "relation": rel, "reason_code": rcode, "reason": rdetail})

    by_id = {e["evidence_id"]: e for e in candidates}
    srcs = {}
    for u in f["used_evidence"]:
        srcs.setdefault(by_id[u["evidence_id"]]["underlying_source"], []).append(u["evidence_id"])
    # Known shared sources only; distinct identifiers do not prove independence.
    f["underlying_sources"] = sorted(srcs)
    f["shared_underlying_sources"] = {k: v for k, v in sorted(srcs.items()) if len(v) > 1}
    f["evidence_origins"] = sorted({by_id[u["evidence_id"]]["origin"] for u in f["used_evidence"]})

    if required is not None and not f["reason_codes"]:
        f["state"] = assess_state(True, [u["relation"] for u in f["used_evidence"]])
        if f["state"] == "unverifiable":
            f["reason_codes"].append("no_usable_observation" if not f["used_evidence"] else "only_inconclusive_observations")
        f["rationale"] = _rationale(f)
    else:
        f["state"] = "unverifiable"
    return f


def _rationale(f):
    n = len(f["used_evidence"])
    s = {"supported": f"Supported: {n} compatible observation(s) of the matched artifact; digest equal and none contradicting.",
         "contradicted": f"Contradicted: a compatible observation of the matched artifact has a different digest (same algorithm); {n} observation(s) used.",
         "conflicting_evidence": "Conflicting: compatible observations of the matched artifact both equal and differ from the declared digest.",
         "unverifiable": "Unverifiable: " + ("no compatible observation of the matched artifact." if not n else
                                             "observations used were inconclusive (digest absent or algorithm differs).")}[f["state"]]
    if f["excluded_evidence"]:
        s += f" {len(f['excluded_evidence'])} candidate observation(s) excluded; see excluded_evidence."
    return s
